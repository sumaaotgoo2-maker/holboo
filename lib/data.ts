export async function getApprovedJobs() {
  const { data, error } = await supabase
    .from("jobs")
    .select("*")
    .eq("status", "approved")
    .order("created_at", { ascending: false });
  if (error) {
    console.error(error.message);
    return [];
  }
  return data ?? [];
}